-- 1. 작품 기본 정보 테이블
CREATE TABLE CONTENT
(
    CONTENT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TMDB_ID          NUMBER,
    CONTENT_TYPE     VARCHAR2(20),
    TITLE            VARCHAR2(300)                       NOT NULL,
    POSTER_IMAGE_URL VARCHAR2(4000),
    SYNOPSIS         CLOB,
    CREATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_CONTENT_TMDB UNIQUE (TMDB_ID, CONTENT_TYPE)
);

-- 2. 작품별 장르 테이블
CREATE TABLE CONTENT_GENRES
(
    CONTENT_ID NUMBER REFERENCES CONTENT (CONTENT_ID) ON DELETE CASCADE,
    GENRE_NAME VARCHAR2(50),
    PRIMARY KEY (CONTENT_ID, GENRE_NAME)
);

-- 3. 작품 출연진 테이블
CREATE TABLE CONTENT_PERSON
(
    PERSON_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENT_ID        NUMBER NOT NULL,
    NAME              VARCHAR2(100),
    CHAR_NAME         VARCHAR2(100),
    PROFILE_IMAGE_URL VARCHAR2(4000),

    CONSTRAINT FK_CONTENT_PERSON_TO_CONTENT FOREIGN KEY (CONTENT_ID) REFERENCES CONTENT (CONTENT_ID) ON DELETE CASCADE
);

-- 4. 작품 에피소드 테이블
CREATE TABLE CONTENT_EPISODE
(
    EPISODE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENT_ID      NUMBER NOT NULL,
    EPISODE_NO      NUMBER,
    TITLE           VARCHAR2(300),
    SUMMARY         VARCHAR2(4000),
    STILL_IMAGE_URL VARCHAR2(4000),

    CONSTRAINT FK_CONTENT_EPISODE_TO_CONTENT FOREIGN KEY (CONTENT_ID) REFERENCES CONTENT (CONTENT_ID) ON DELETE CASCADE

);

-- 유저 테이블
CREATE TABLE USERS
(
    USER_ID    VARCHAR2(50)                NOT NULL,
    EMAIL      VARCHAR2(100)               NOT NULL,
    USERNAME   VARCHAR2(30)                NOT NULL,
    PASSWORD   VARCHAR2(150),
    PHONE      VARCHAR2(20),
    BAN_YN     VARCHAR2(1)  DEFAULT 'N',
    ROLE       VARCHAR2(10) DEFAULT 'USER' NOT NULL,
    CREATED_AT TIMESTAMP    DEFAULT SYSTIMESTAMP,
    UPDATED_AT TIMESTAMP,
    DEL_YN     VARCHAR2(1)  DEFAULT 'N'    NOT NULL,
    DELETED_AT TIMESTAMP,

    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_BAN_YN CHECK (BAN_YN IN ('Y', 'N')),
    CONSTRAINT CK_USERS_DEL_YN CHECK (DEL_YN IN ('Y', 'N'))
);

CREATE TABLE USER_REFRESH_TOKEN
(
    USER_ID    VARCHAR2(50)                   NOT NULL,
    JTI        VARCHAR2(36)                   NOT NULL,
    EXPIRES_AT TIMESTAMP                      NOT NULL,
    REVOKED_YN CHAR(1)   DEFAULT 'N'          NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REVOKED_AT TIMESTAMP                      NULL,
    CONSTRAINT PK_USER_REFRESH_TOKEN PRIMARY KEY (USER_ID, JTI)
);
