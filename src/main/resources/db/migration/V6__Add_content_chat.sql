CREATE TABLE CHAT_MESSAGE (
    MESSAGE_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CONTENT_ID NUMBER NOT NULL,
    USER_ID VARCHAR2(50),
    BODY VARCHAR2(500 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CHAT_CONTENT FOREIGN KEY (CONTENT_ID) REFERENCES CONTENT(CONTENT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CHAT_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE SET NULL
);

CREATE INDEX IX_CHAT_CONTENT_MESSAGE ON CHAT_MESSAGE(CONTENT_ID, MESSAGE_ID);
CREATE INDEX IX_CHAT_USER_CREATED ON CHAT_MESSAGE(USER_ID, CREATED_AT);
