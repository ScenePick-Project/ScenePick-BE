CREATE TABLE REVIEW_NOTIFICATION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID VARCHAR2(50) NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    ACTOR_ID VARCHAR2(50) NOT NULL,
    REVIEW_ID NUMBER NOT NULL,
    TYPE VARCHAR2(30) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    READ_AT TIMESTAMP,
    CONSTRAINT CK_NOTIFICATION_TYPE CHECK (TYPE IN ('REVIEW_LIKE', 'REVIEW_BOOKMARK')),
    CONSTRAINT CK_NOTIFICATION_SELF CHECK (USER_ID <> ACTOR_ID)
);
CREATE INDEX IX_NOTIFICATION_OWNER ON REVIEW_NOTIFICATION(USER_ID, CREATED_AT DESC, ID DESC);
CREATE INDEX IX_NOTIFICATION_UNREAD ON REVIEW_NOTIFICATION(USER_ID, READ_AT);
