CREATE TABLE MOMENT
(
    MOMENT_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID     VARCHAR2(50)                     NOT NULL,
    CONTENT_ID  NUMBER                           NOT NULL,
    YOUTUBE_ID  VARCHAR2(11)                     NOT NULL,
    START_TIME  NUMBER(10)                       NOT NULL,
    END_TIME    NUMBER(10)                       NOT NULL,
    MEMO        CLOB,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP   NOT NULL,
    UPDATED_AT  TIMESTAMP,
    DEL_YN      VARCHAR2(1) DEFAULT 'N'           NOT NULL,
    DELETED_AT  TIMESTAMP,

    CONSTRAINT FK_MOMENT_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_MOMENT_CONTENT FOREIGN KEY (CONTENT_ID) REFERENCES CONTENT (CONTENT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_MOMENT_TIME CHECK (START_TIME >= 0 AND END_TIME > START_TIME),
    CONSTRAINT CK_MOMENT_DEL_YN CHECK (DEL_YN IN ('Y', 'N'))
);

CREATE INDEX IX_MOMENT_USER_CURSOR ON MOMENT (USER_ID, DEL_YN, CREATED_AT DESC, MOMENT_ID DESC);
CREATE INDEX IX_MOMENT_CONTENT_CURSOR ON MOMENT (USER_ID, CONTENT_ID, DEL_YN, CREATED_AT DESC, MOMENT_ID DESC);
CREATE INDEX IX_MOMENT_VIDEO_CURSOR ON MOMENT (USER_ID, YOUTUBE_ID, DEL_YN, CREATED_AT DESC, MOMENT_ID DESC);
