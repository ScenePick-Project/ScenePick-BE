ALTER TABLE REVIEW ADD (RATING NUMBER(2,1));
ALTER TABLE REVIEW ADD CONSTRAINT CK_REVIEW_RATING CHECK
    (RATING IS NULL OR (RATING BETWEEN 0.5 AND 5 AND MOD(RATING, 0.5) = 0));

CREATE TABLE USER_FOLLOW (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID VARCHAR2(50) NOT NULL REFERENCES USERS(USER_ID),
    TARGET_ID VARCHAR2(50) NOT NULL REFERENCES USERS(USER_ID),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_USER_FOLLOW UNIQUE (USER_ID, TARGET_ID),
    CONSTRAINT CK_NO_SELF_FOLLOW CHECK (USER_ID <> TARGET_ID)
);
CREATE INDEX IX_FOLLOW_OWNER ON USER_FOLLOW(USER_ID, CREATED_AT DESC, ID DESC);
CREATE INDEX IX_FOLLOW_TARGET ON USER_FOLLOW(TARGET_ID, CREATED_AT DESC, ID DESC);
CREATE TABLE REVIEW_BOOKMARK (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID VARCHAR2(50) NOT NULL REFERENCES USERS(USER_ID),
    REVIEW_ID NUMBER NOT NULL REFERENCES REVIEW(REVIEW_ID),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_REVIEW_BOOKMARK UNIQUE (USER_ID, REVIEW_ID)
);
CREATE INDEX IX_REVIEW_BOOKMARK_OWNER ON REVIEW_BOOKMARK(USER_ID, CREATED_AT DESC, ID DESC);
CREATE TABLE TRACK_BOOKMARK (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID VARCHAR2(50) NOT NULL REFERENCES USERS(USER_ID),
    TRACK_ID VARCHAR2(100 CHAR) NOT NULL,
    TRACK_NAME VARCHAR2(300 CHAR) NOT NULL,
    ARTIST VARCHAR2(300 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_TRACK_BOOKMARK UNIQUE (USER_ID, TRACK_ID)
);
CREATE INDEX IX_TRACK_BOOKMARK_OWNER ON TRACK_BOOKMARK(USER_ID, CREATED_AT DESC, ID DESC);
CREATE INDEX IX_REVIEW_OWNER ON REVIEW(USER_ID, DEL_YN, CREATED_AT DESC, REVIEW_ID DESC);
